Platform::Platform() : left_(0), right_(0), top_(0), bottom_(0) {}

Platform::Platform(const Platform& other)
    : left_(other.left_),
      right_(other.right_),
      top_(other.top_),
      bottom_(other.bottom_),
      boxCollider_(new BoxCollider(pro2::Pt{other.left_, other.top_},
                                   pro2::Pt{other.right_, other.bottom_})) {}

Platform::Platform(int left, int right, int top, int bottom)
    : left_(left),
      right_(right),
      top_(top),
      bottom_(bottom),
      boxCollider_(new BoxCollider(pro2::Pt{left, top}, pro2::Pt{right, bottom})) {}

void Platform::paint(pro2::Window& window, bool debug) const {
    for (int i = top_ + 1; i <= bottom_; i++) {
        for (int j = left_; j <= right_; j++) {
            if (j < left_ + 16 && i < top_ + 1 + 16) {
                int col = platform_clear_border[(i - top_ - 1) % 16][(j - left_) % 16];
                if (col != _) {
                    window.set_pixel({j, i}, col);
                }
            } else if (j >= right_ - 15 && i < top_ + 1 + 16) {
                int col = platform_clear_border[(i - top_ - 1) % 16][15 - (j - (right_ - 15))];

                // cout << (15 - (static_cast<unsigned>(j - left_) % 16)) << endl;
                if (col != _) {
                    window.set_pixel({j, i}, col);
                }
            } else if (j < left_ + 16) {
                int col = platform_clear_side[(i - top_ - 1) % 16][(j - left_) % 16];
                if (col != _) {
                    window.set_pixel({j, i}, col);
                }
            } else if (j >= right_ - 15) {
                int col = platform_clear_side[(i - top_ - 1) % 16][15 - (j - (right_ - 15))];

                // cout << (15 - (static_cast<unsigned>(j - left_) % 16)) << endl;
                if (col != _) {
                    window.set_pixel({j, i}, col);
                }
            } else if (i < top_ + 1 + 16) {
                int col = platform_clear_top[(i - top_ - 1) % 16][(j - left_) % 16];
                if (col != _) {
                    window.set_pixel({j, i}, col);
                }
            } else {
                int col = platform_clear_mid_1_[(i - top_ - 1) % 16][(j - left_) % 16];
                if (col != _) {
                    window.set_pixel({j, i}, col);
                }
            }
        }
    }
    if (debug) {
        boxCollider_->printDebugLines(window);
    }
}

bool Platform::has_crossed_floor_downwards(pro2::Pt plast, pro2::Pt pcurr) const {
    // return (left_ <= plast.x && plast.x <= right_) && (left_ <= pcurr.x && pcurr.x <= right_) &&
    //        (plast.y <= top_ && pcurr.y >= top_);

    if (pcurr.y <= plast.y) {
        return false;
    }

    if (boxCollider_->collidingWith(new BoxCollider{plast, pcurr})) {
        return true;
    }
    return false;
}

bool Platform::has_crossed_platform(pro2::Pt plast, pro2::Pt pcurr) const {
    bool wasColliding = !boxCollider_->collidingWith(new BoxCollider({plast, plast}));
    bool isColliding = boxCollider_->collidingWith(new BoxCollider({pcurr, pcurr}));

    return !wasColliding && isColliding;
}

bool Platform::is_pt_inside(pro2::Pt pt) const {
    return left_ <= pt.x && pt.x <= right_ && top_ <= pt.y && pt.y <= bottom_;
}

BoxCollider *Platform::getCollider() const {
    return boxCollider_;
}

bool Platform::has_crossed_block_sideways(pro2::Pt plast, pro2::Pt pcurr) const {
    if (pcurr.x == plast.x) {
        return false;
    }

    // Check collision along the horizontal movement
    pro2::Pt from = plast;
    pro2::Pt to = pcurr;
    if (boxCollider_->collidingWith(new BoxCollider{from, to})) {
        return true;
    }
    return false;
}
